fn evaluate_solution(problem: &Problem, groups: Vec<Vec<Idx>>) -> Solution {
    let graph = &problem.graph;

    let mut parents = vec![graph.substation(); graph.node_count()];
    for group in groups {
        mecanism::prim(problem, &group, &mut parents);
    }

    let mut solution = Solution::from_parents(parents, problem);

    mecanism::evaluate(problem, &mut solution);

    solution
}

#[derive(Clone, Copy)]
pub(crate) enum Direction {
    Clockwise,
    CounterClockwise,
}

// Converts the direction into a mathematical step for array traversal.
impl From<Direction> for isize {
    fn from(value: Direction) -> Self {
        match value {
            Direction::Clockwise => 1,
            Direction::CounterClockwise => -1,
        }
    }
}

pub(crate) fn initialize_groups(
    turbines: &[(Idx, Angle)],
    dir: Direction,
    start_idx: isize,
    tpg: usize,
) -> Vec<Vec<Idx>> {
    // Initialization of groups.
    let mut groups: Vec<Vec<Idx>> = Vec::new();
    let mut current_group = Vec::with_capacity(tpg);

    assert!(isize::try_from(turbines.len()).is_ok());
    #[allow(clippy::cast_possible_wrap)]
    let n = turbines.len() as isize;
    let step: isize = dir.into(); // Gets +1 or -1 via the From trait.

    for i in 0..n {
        // start_idx + (i * step): Shifts the index in the chosen direction.
        // rem_euclid(n): Safely wraps the index around the array, correctly
        // handling negative values generated by CounterClockwise.
        let idx = (start_idx + i * step).rem_euclid(n) as usize;

        // Adicione o indice da turbina ao grupo
        current_group.push(turbines[idx].0);

        // Save the group if it reaches the target size (tpg)
        // or if it is the last iteration (i == n - 1) to prevent data loss.
        if current_group.len() == tpg || i == n - 1 {
            groups.push(current_group.clone());
            current_group.clear();
        }
    }

    groups
}
